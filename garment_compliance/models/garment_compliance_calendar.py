"""
Compliance Alert System / Compliance Calendar (SRS1 sec. 18, SRS2 secs.
10, 19) — garment.compliance.calendar. Certificate-expiry (90/60/30-day),
audit-due and inspection-due reminders. Entries are auto-generated by a
daily ir.cron (see data/ir_cron_data.xml) and can also be created
manually for ad-hoc renewal reminders.
"""
from datetime import timedelta

from odoo import fields, models

REMINDER_THRESHOLDS = (90, 60, 30, 15)


class GarmentComplianceCalendar(models.Model):
    _name = 'garment.compliance.calendar'
    _description = 'Garment Compliance Calendar / Renewal Reminder'
    _order = 'due_date'

    name = fields.Char(string='Reminder', required=True)
    event_type = fields.Selection([
        ('certificate_expiry', 'Certificate / License Expiry'),
        ('audit_due', 'Audit Due'),
        ('requirement_due', 'Requirement Due'),
        ('inspection_due', 'Inspection Due'),
    ], string='Event Type', required=True)
    certificate_id = fields.Many2one('garment.compliance.certificate', string='Certificate')
    audit_id = fields.Many2one('garment.compliance.audit', string='Audit')
    requirement_id = fields.Many2one('garment.compliance.requirement', string='Requirement')
    fire_equipment_id = fields.Many2one('garment.compliance.fire.equipment', string='Fire Equipment')
    building_inspection_id = fields.Many2one('garment.compliance.building.inspection', string='Building Inspection')
    department_id = fields.Many2one('garment.hr.department', string='Department')
    responsible_user_id = fields.Many2one('res.users', string='Responsible Person')
    due_date = fields.Date(string='Due Date', required=True)
    days_remaining = fields.Integer(string='Days Remaining', compute='_compute_days_remaining')
    status = fields.Selection([
        ('pending', 'Pending'), ('reminded', 'Reminder Sent'), ('completed', 'Completed'), ('overdue', 'Overdue'),
    ], string='Status', default='pending')
    notes = fields.Char(string='Notes')

    def _compute_days_remaining(self):
        today = fields.Date.context_today(self)
        for rec in self:
            rec.days_remaining = (rec.due_date - today).days if rec.due_date else 0

    def action_mark_completed(self):
        self.write({'status': 'completed'})

    # ------------------------------------------------------------------
    # Compliance Alert System (SRS1 sec. 18) / Compliance Notification
    # System (SRS2 sec. 19) — daily scan, called by ir.cron.
    # ------------------------------------------------------------------
    def _cron_generate_reminders(self):
        today = fields.Date.context_today(self)
        horizon = today + timedelta(days=max(REMINDER_THRESHOLDS))

        certificates = self.env['garment.compliance.certificate'].search([
            ('expiry_date', '!=', False), ('expiry_date', '<=', horizon),
        ])
        for cert in certificates:
            self._upsert_reminder('certificate_expiry', cert.expiry_date, certificate_id=cert.id,
                                   name='%s Expiring' % cert.name, responsible_user_id=cert.responsible_user_id.id)

        audits = self.env['garment.compliance.audit'].search([
            ('status', '!=', 'closed'), ('audit_date', '!=', False), ('audit_date', '<=', horizon),
        ])
        for audit in audits:
            self._upsert_reminder('audit_due', audit.audit_date, audit_id=audit.id,
                                   name='%s Due' % audit.name, responsible_user_id=audit.auditor_id.id)

        fire_equipment = self.env['garment.compliance.fire.equipment'].search([
            ('next_inspection_date', '!=', False), ('next_inspection_date', '<=', horizon),
        ])
        for equipment in fire_equipment:
            self._upsert_reminder('inspection_due', equipment.next_inspection_date, fire_equipment_id=equipment.id,
                                   name='%s Inspection Due' % equipment.name,
                                   responsible_user_id=equipment.responsible_user_id.id)

        inspections = self.env['garment.compliance.building.inspection'].search([
            ('next_inspection_date', '!=', False), ('next_inspection_date', '<=', horizon),
        ])
        for inspection in inspections:
            self._upsert_reminder('inspection_due', inspection.next_inspection_date, building_inspection_id=inspection.id,
                                   name='%s Inspection Due' % inspection.building_id.name)

        overdue = self.search([('status', 'in', ('pending', 'reminded')), ('due_date', '<', today)])
        overdue.write({'status': 'overdue'})

    def _upsert_reminder(self, event_type, due_date, name, responsible_user_id=None, **link_vals):
        domain = [('event_type', '=', event_type), ('due_date', '=', due_date), ('status', 'in', ('pending', 'reminded'))]
        for field, value in link_vals.items():
            domain.append((field, '=', value))
        existing = self.search(domain, limit=1)
        vals = dict(link_vals, event_type=event_type, due_date=due_date, name=name)
        if responsible_user_id:
            vals['responsible_user_id'] = responsible_user_id
        if existing:
            existing.write({'status': 'reminded'})
        else:
            self.create(vals)
